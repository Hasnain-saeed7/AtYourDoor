async function runAgent() {
  console.log('🤖 TrustHire Translation Agent')
  console.log('📡 Using Groq — llama-3.3-70b-versatile\n')

  const allTranslations = {}
  let totalStrings = 0

  for (let i = 0; i < TARGET_FILES.length; i++) {
    const filePath = TARGET_FILES[i]

    if (!fs.existsSync(filePath)) {
      console.log(`⚠️  Skipping ${filePath} — not found`)
      continue
    }

    console.log(`📄 [${i + 1}/${TARGET_FILES.length}] ${filePath}`)
    const content = fs.readFileSync(filePath, 'utf-8')

    const strings = await extractStrings(content)
    console.log(`   Found ${strings.length} strings`)

    if (strings.length > 0) {
      const translated = await translateToUrdu(strings)
      const count = Object.keys(translated).length
      console.log(`   Translated ${count} strings ✓`)
      Object.assign(allTranslations, translated)
      totalStrings += strings.length
    }

    // Wait 15 seconds between files
    if (i < TARGET_FILES.length - 1) {
      console.log(`   ⏳ Waiting 15s before next file...`)
      await wait(15000)
    }
  }

  console.log(`\n📊 Total strings: ${totalStrings}`)
  console.log(`📊 Total translations: ${Object.keys(allTranslations).length}`)
  console.log('\n🔨 Generating files...\n')

  await buildTranslationsFile(allTranslations)
  buildLanguageContext()
  buildLanguageToggle()

  console.log('\n🎉 Done! Your app is ready for Urdu.')
  console.log('\n📋 Next steps:')
  console.log('1. Add LanguageProvider to src/app/layout.tsx')
  console.log('2. Add LanguageToggle to your navbars')
  console.log('3. Replace hardcoded text with t("key") in components')
}

runAgent().catch(console.error)